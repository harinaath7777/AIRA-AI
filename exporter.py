# MARKDOWN EXPORT
# ─────────────────────────────────────────────────────────────

def export_markdown(result, followups=None):
    """
    Generate a Markdown report from a research result dict.
    Returns a UTF-8 string.
    """
    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")
    lines = []

    lines.append(f"# AIRA AI Research Report")
    lines.append(f"")
    lines.append(f"**Question:** {result.get('query', '')}")
    lines.append(f"")
    lines.append(f"**Mode:** {result.get('mode', 'normal').capitalize()}  ")
    lines.append(f"**Research Time:** {result.get('time', 0):.1f}s  ")
    lines.append(f"**Generated:** {now}  ")
    lines.append(f"**Sources Found:** {result.get('total_sources', 0)}  ")
    lines.append(f"**Passages Analysed:** {result.get('total_passages', 0)}")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Summary
    lines.append("## Answer")
    lines.append("")
    summary = result.get("summary", "").strip()
    lines.append(summary if summary else "_No summary available._")
    lines.append("")
    lines.append("---")
    lines.append("")

    # Sources
    sources = result.get("sources", [])
    if sources:
        lines.append("## Sources")
        lines.append("")
        for i, s in enumerate(sources, 1):
            title = s.get("title") or s.get("domain") or s.get("url", "")
            url = s.get("url", "")
            score = s.get("score", 0)
            lines.append(f"{i}. **[{title}]({url})**  ")
            lines.append(f"   Domain: `{s.get('domain', '')}` | Relevance: {score:.2%}")
            lines.append("")

    lines.append("---")
    lines.append("")

    # Relevant Passages
    passages = result.get("passages", [])
    if passages:
        lines.append("## Relevant Passages")
        lines.append("")
        for p in passages:
            domain = p.get("url", "").replace("https://", "").replace("http://", "").split("/")[0]
            lines.append(f"### {domain}")
            lines.append(f"**Relevance:** {p.get('score', 0):.2%}  ")
            lines.append(f"**Source:** <{p.get('url', '')}>")
            lines.append("")
            lines.append(f"> {p.get('passage', '')}")
            lines.append("")

    # Follow-ups
    if followups:
        lines.append("---")
        lines.append("")
        lines.append("## Follow-up Questions")
        lines.append("")
        for fu in followups:
            lines.append(f"### Q: {fu.get('question', '')}")
            answer = fu.get("answer", {})
            lines.append("")
            lines.append(answer.get("summary", "_No answer available._"))
            lines.append("")

    lines.append("---")
    lines.append("")
    lines.append("_Report generated by AIRA AI Research Assistant_")

    return "\n".join(lines)


# ─────────────────────────────────────────────────────────────
# SAFE TEXT HELPER
# ─────────────────────────────────────────────────────────────

def _safe(text: str) -> str:
    """
    Sanitize a string for fpdf2's latin-1 (cp1252) encoder.
    Normalises unicode quotes/dashes to ASCII, then encodes with 'replace'
    to drop any remaining non-encodable characters — prevents crashes on
    text scraped from websites that contains smart quotes, emoji, etc.
    """
    if not isinstance(text, str):
        text = str(text)
    replacements = {
        "\u2018": "'", "\u2019": "'", "\u201c": '"', "\u201d": '"',
        "\u2013": "-", "\u2014": "-", "\u2026": "...", "\u00a0": " ",
        "\u2022": "*", "\u2192": "->", "\u2190": "<-", "\u00b7": "-",
        "\u00e2\u0080\u0099": "'",  # mojibake
    }
    for src, dst in replacements.items():
        text = text.replace(src, dst)
    return text.encode("latin-1", errors="replace").decode("latin-1")


