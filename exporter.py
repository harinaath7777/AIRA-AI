def export_pdf(result, followups=None):
    """
    Generate a PDF report. Returns raw bytes.
    Requires: fpdf2  (pip install fpdf2)
    """
    try:
        from fpdf import FPDF
    except ImportError:
        raise ImportError("fpdf2 is required: pip install fpdf2")

    class _SafePDF(FPDF):
        def multi_cell(self, *args, **kwargs):
            kwargs.setdefault("new_x", "LMARGIN")
            kwargs.setdefault("new_y", "NEXT")
            return super().multi_cell(*args, **kwargs)

    now = datetime.utcnow().strftime("%Y-%m-%d %H:%M UTC")

    pdf = _SafePDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()
    pdf.set_margins(20, 20, 20)

    # ── Title ─────────────────────────────────────────────────
    pdf.set_font("Helvetica", "B", 20)
    pdf.set_text_color(30, 30, 60)
    pdf.multi_cell(0, 12, "AIRA AI Research Report", align="C")
    pdf.ln(4)

    # ── Metadata ──────────────────────────────────────────────
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(100, 100, 100)
    pdf.multi_cell(
        0, 6,
        f"Generated: {now}  |  Mode: {result.get('mode','normal').capitalize()}  "
        f"|  Time: {result.get('time',0):.1f}s  "
        f"|  Sources: {result.get('total_sources',0)}",
        align="C",
    )
    pdf.ln(6)

    # ── Separator ─────────────────────────────────────────────
    pdf.set_draw_color(180, 180, 200)
    pdf.line(20, pdf.get_y(), 190, pdf.get_y())
    pdf.ln(6)

    # ── Question ──────────────────────────────────────────────
    pdf.set_font("Helvetica", "B", 13)
    pdf.set_text_color(40, 40, 80)
    pdf.multi_cell(0, 8, "Research Question", align="L")
    pdf.ln(2)
    pdf.set_font("Helvetica", "", 12)
    pdf.set_text_color(20, 20, 40)
    pdf.multi_cell(0, 7, _safe(result.get("query", "")), align="L")
    pdf.ln(6)

    # ── Summary ───────────────────────────────────────────────
    _pdf_section(pdf, "Answer", _safe(result.get("summary", "No summary available.")))

    # ── Sources ───────────────────────────────────────────────
    sources = result.get("sources", [])
    if sources:
        pdf.set_font("Helvetica", "B", 13)
        pdf.set_text_color(40, 40, 80)
        pdf.multi_cell(0, 8, "Sources", align="L")
        pdf.ln(2)
        pdf.set_font("Helvetica", "", 10)
        pdf.set_text_color(20, 20, 40)
        for i, s in enumerate(sources, 1):
            title = _safe(s.get("title") or s.get("domain") or s.get("url", ""))
            score = s.get("score", 0)
            pdf.multi_cell(
                0, 6,
                f"{i}. {title} ({_safe(s.get('domain',''))}) - Relevance: {score:.0%}",
                align="L",
            )
            pdf.set_font("Helvetica", "I", 8)
            pdf.set_text_color(0, 80, 180)
            pdf.multi_cell(0, 5, _safe(s.get("url", "")), align="L")
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(20, 20, 40)
            pdf.ln(2)
        pdf.ln(4)

    # ── Passages ──────────────────────────────────────────────
    passages = result.get("passages", [])
    if passages:
        pdf.set_font("Helvetica", "B", 13)
        pdf.set_text_color(40, 40, 80)
        pdf.multi_cell(0, 8, "Relevant Passages", align="L")
        pdf.ln(2)
        for p in passages:
            domain = _safe(
                p.get("url", "").replace("https://", "").replace("http://", "").split("/")[0]
            )
            pdf.set_font("Helvetica", "B", 10)
            pdf.set_text_color(60, 60, 120)
            pdf.multi_cell(0, 6, f"{domain} - {p.get('score', 0):.0%} relevance", align="L")
            pdf.set_font("Helvetica", "I", 9)
            pdf.set_text_color(100, 100, 100)
            pdf.multi_cell(0, 5, _safe(p.get("url", "")), align="L")
            pdf.set_font("Helvetica", "", 10)
            pdf.set_text_color(30, 30, 50)
            pdf.multi_cell(0, 6, _safe(p.get("passage", "")), align="L")
            pdf.ln(4)

    # ── Follow-ups ─────────────────────────────────────────────
    if followups:
        pdf.add_page()
        pdf.set_font("Helvetica", "B", 14)
        pdf.set_text_color(40, 40, 80)
        pdf.multi_cell(0, 8, "Follow-up Questions", align="L")
        pdf.ln(4)
        for fu in followups:
            pdf.set_font("Helvetica", "B", 11)
            pdf.set_text_color(30, 80, 150)
            pdf.multi_cell(0, 7, f"Q: {_safe(fu.get('question', ''))}", align="L")
            pdf.ln(1)
            answer = fu.get("answer", {})
            _pdf_section(pdf, "A", _safe(answer.get("summary", "No answer.")), title_size=10)

    # ── Footer ────────────────────────────────────────────────
    pdf.set_y(-20)
    pdf.set_font("Helvetica", "I", 8)
    pdf.set_text_color(150, 150, 150)
    pdf.multi_cell(0, 5, "Generated by AIRA AI Research Assistant", align="C")

    return bytes(pdf.output())


def _pdf_section(pdf, title, body, title_size=13):
    pdf.set_font("Helvetica", "B", title_size)
    pdf.set_text_color(40, 40, 80)
    pdf.multi_cell(0, 8, title, align="L")
    pdf.ln(2)
    pdf.set_font("Helvetica", "", 10)
    pdf.set_text_color(20, 20, 40)
    pdf.multi_cell(0, 6, body, align="L")
    pdf.ln(6)
